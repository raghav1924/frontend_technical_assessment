export const DraggableNode = ({ type, label, icon: CustomIcon }) => {
  const onDragStart = (event, nodeType) => {
    const appData = { nodeType };
    event.target.style.cursor = 'grabbing';
    event.dataTransfer.setData('application/reactflow', JSON.stringify(appData));
    event.dataTransfer.effectAllowed = 'move';
  };

  const IconComponent = CustomIcon || NODE_ICONS[type];

  return (
    <div
      className={`vs-node-tile-card ${type}`}
      onDragStart={(event) => onDragStart(event, type)}
      onDragEnd={(event) => (event.target.style.cursor = 'grab')}
      draggable
      title={`Drag to add ${label}`}
    >
      <div className="vs-node-tile-icon">
        {IconComponent ? <IconComponent /> : <span>◻</span>}
      </div>
      <span className="vs-node-tile-label">{label}</span>
    </div>
  );
};
